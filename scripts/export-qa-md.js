/**
 * Writes knowledge/faq/qa-bank.md from the question bank, so the cloud RAG index
 * (node scripts/ingest.js) learns the same hand-written answers as the local engine.
 * Project and FAQ entries are skipped: their source markdown files are already indexed.
 *
 *   node scripts/export-qa-md.js && node scripts/ingest.js
 */
const fs = require('fs');
const path = require('path');
const { buildBank } = require('../lib/qa-bank');

const rows = buildBank().filter((e) => !e.id.startsWith('faq-') && !e.id.startsWith('project-') && e.topic !== 'meta');
let md = `---
title: Question Bank (generated)
category: faq
visibility: public
importance: high
source: generated by scripts/export-qa-md.js
---

# Question Bank

Generated from lib/qa-bank.js. Do not edit by hand: edit the bank and run \`node scripts/export-qa-md.js\`.

`;
for (const e of rows) {
  md += `### ${e.q[0]}\n\nAlso asked as: ${e.q.slice(1, 5).join(' | ')}\n\n${e.a}\n\n`;
}
const out = path.join(__dirname, '..', 'knowledge', 'faq', 'qa-bank.md');
fs.writeFileSync(out, md);
console.log(`Wrote ${rows.length} entries to ${path.relative(process.cwd(), out)}`);
